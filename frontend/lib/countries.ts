export function countryFlag(code: string): string {
  if (!/^[A-Z]{2}$/.test(code)) return "🌍";
  return String.fromCodePoint(...code.split("").map((char) => 127397 + char.charCodeAt(0)));
}

export function findCountryByName(value?: string | null): CountryOption | null {
  const key = String(value || "").trim();
  if (!key) return null;
  const directCode = /^[A-Za-z]{2}$/.test(key) ? key.toUpperCase() : COUNTRY_ALIASES[key];
  if (directCode) return COUNTRY_OPTIONS.find((item) => item.code === directCode) || null;
  const folded = key.toLocaleLowerCase("fr-FR");
  return COUNTRY_OPTIONS.find((item) => item.name.toLocaleLowerCase("fr-FR") === folded || item.label.toLocaleLowerCase("fr-FR") === folded) || null;
}

export function getCountryByCode(code?: string | null): CountryOption | null {
  const normalized = String(code || "").trim().toUpperCase();
  return COUNTRY_OPTIONS.find((item) => item.code === normalized) || null;
}

export function inferCountryFromPhone(value?: string | null): CountryOption | null {
  const digits = String(value || "").replace(/\D/g, "");
  if (!digits) return null;
  const candidates = COUNTRY_OPTIONS
    .filter((item) => item.dialCode)
    .sort((a, b) => b.dialCode.length - a.dialCode.length);
  return candidates.find((item) => digits.startsWith(item.dialCode.replace(/\D/g, ""))) || null;
}

export function phoneDigits(value: string): string {
  return String(value || "").replace(/\D/g, "").slice(0, 15);
}

export function buildE164(countryCode: string, nationalNumber: string): string {
  const country = getCountryByCode(countryCode);
  const national = phoneDigits(nationalNumber);
  if (!country?.dialCode || !national) return "";
  return `${country.dialCode}${national}`;
}
